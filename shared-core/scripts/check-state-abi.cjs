module.exports = function stateAbiSmoke(core, assert) {
    const security = core.parentalDefaults();
    assert.equal(core.parentalValidate(security).schema, 1);
    assert.equal(core.parentalValidPin('1234'), true);
    assert.equal(core.parentalChannelId('source:1'), true);
    assert.equal(core.parentalProtected(security, '', 'settings'), false);
    assert.equal(core.parentalBlock(1e15, 1000), 301000);
    assert.equal(core.parentalRetry(1100, 1000), 1);
    assert.equal(core.parentalFailedCount(29), 30);
    assert.equal(core.parentalFailedBlock(5, 0, 1000), 31000);
    const session = new core.BrowserParentalSession();
    session.observe('identity', 'source'); session.clock(1000); session.grant(1000, 5);
    assert.equal(session.expires(1001), 301000); session.clock(NaN); assert.equal(session.expires(1001), 0); session.lock();
    const state = core.browserStateDefaults(security);
    assert.equal(core.browserStateFonts().length, 7);
    assert.equal(core.validateBrowserState(state, core.parentalDefaults, core.parentalValidate).schema, 1);
    assert.equal(core.favoriteListName(' Test '), 'Test');
    core.favoriteListChange(state, 'browser', 'add', 'New'); core.editFavoriteSelection(state.favorites.New, 'source:1', 'add');
    core.moveFavoriteSelection(state.favorites.New, 'source:1', 0);
    const classic = core.loadClassicFavoriteLists(null, []); core.favoriteListCurrent(classic);
    assert.equal(core.favoriteListOrder(classic.lists, classic.order)[0], 'Favorites');
    assert.equal(core.pruneBrowserSources(state, state).schema, 1);
    assert.equal(core.exportBrowserState(state, false).sources.length, 0);
    assert.equal(core.removeBrowserHistory(core.recordBrowserHistory([], 'source:1', 'Name', 100), 'source:1').length, 0);
    const channel = { id:'source:1',sourceId:'source',kind:'live',name:'News',url:'https://stream' }, reference=core.channelReference(channel,'source');
    assert.equal(core.restoreChannelIndex([channel], reference), 0);
    state.sources=[{id:'source',type:'m3u',url:'https://list'}]; state.favorites.default=['source:1'];
    assert.equal(core.channelDescriptor(channel,'source',()=> '1-1').stream,'1-1');
    state.channelReferences=core.rememberChannelIdentity(state,[channel],'source',()=> '1-1');
    assert.equal(core.reconcileChannelIdentity(state,[channel],'source',()=> '1-1').report.unresolved,0);
    assert.equal(core.channelIdentityPermission(null,'source:1',[]),'source:1');
    assert.equal(core.libraryEdit('source:1',{name:'New'}).name,'New');
    assert.equal(core.libraryDecorate([channel],{},false)[0].name,'News');
    assert.equal(core.libraryReminderId('source:1',100),'source:1@100');
    assert.equal(core.libraryToggleReminder([],channel,{start:100,end:200,title:'Programme'}).length,1);
    const entry=core.libraryPreferenceEntry(reference,null,'zoom',1.25);
    assert.equal(core.librarySavePreference([],entry,null).length,1);
    assert.equal(core.libraryPreferenceIndex([entry],channel,reference,[channel]),0);
    assert.equal(core.previewLegacySettings({ottplaylang:'_rus'},false,()=>core.browserStateDefaults(core.parentalDefaults()),value=>core.validateBrowserState(value,core.parentalDefaults,core.parentalValidate),JSON.parse,value=>value).proposed.settings.language,'ru');
    assert.equal(core.classicPortableKey('commandServerToken',true),false);
    assert.equal(core.classicPortableSnapshot({ordinary:'ok',commandServerToken:'private'},true).ordinary,'ok');
    assert.equal(core.classicInstallationState({sLocalHttpEnabled:1},true).sLocalHttpEnabled,'1');
    assert.equal(core.classicImportEnvelope({version:1,settings:{}}),true);
    assert.equal(core.classicParentalPrompt(1,'1234',false),true);
    assert.equal(core.classicHistorySelection([], {stream_url:'url'},'url',0,2).limit,20);
};
